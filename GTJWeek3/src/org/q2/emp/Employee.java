package org.q2.emp;

public class Employee {

	public void empid() {
		System.out.println("Jeyanth's employee Id is 96893");
	}
	public void empid(int a) {
		System.out.println("Jeyanth's employee id "+a);
	}
	public static void main(String[] args) {
		
		Employee emp=new Employee();
		emp.empid();
		emp.empid(968934);
		
	}

}
